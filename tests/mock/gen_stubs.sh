#!/bin/bash
# Writes C stubs for every atg_* in csrc/libtch/torch_api_generated.h that
# tests/mock/mock_tch.c does not implement. Each stub sets the error slot to
# "mock: not implemented: <name>" and returns 0 / NULL.
# Usage: gen_stubs.sh <header> <mock_tch.c> <output.c>
set -euo pipefail
header=$1
impl=$2
out=$3
implemented=$(grep -oE '^(void|tensor \*|int|int64_t|double) ?atg_[a-z0-9_]+' "$impl" | grep -oE 'atg_[a-z0-9_]+' | sort -u)
{
  echo '/* GENERATED by tests/mock/gen_stubs.sh, do not edit. */'
  echo '#include <stddef.h>'
  echo '#include <stdint.h>'
  echo '#include "torch_api_generated.h"'
  echo 'void mock_unimpl(const char *name);'
  grep -E '^(void|tensor \*|int|int64_t|double) ?atg_' "$header" | while IFS= read -r line; do
    name=$(echo "$line" | grep -oE 'atg_[a-z0-9_]+' | head -1)
    if grep -qx "$name" <<< "$implemented"; then continue; fi
    ret=$(echo "$line" | sed -E 's/^(void|tensor \*|int|int64_t|double) ?atg_.*/\1/')
    sig=$(echo "$line" | sed -E 's/\(tensor \*,/(tensor *out__,/; s/\(tensor \*\)/(tensor *out__)/; s/;$//')
    case "$ret" in
      void) body="{ mock_unimpl(\"$name\"); }" ;;
      "tensor *") body="{ mock_unimpl(\"$name\"); return NULL; }" ;;
      *) body="{ mock_unimpl(\"$name\"); return 0; }" ;;
    esac
    echo "$sig $body"
  done
} > "$out"
